def load_ra_organizations(apps, schema_editor):
    """
    Load RA organization data from JSON file.

    Place your JSON file at: api/network/fixtures/ra_orgs_data.json
    Generated by: python manage.py extract_ra_orgs <pdf_path> --out_path api/network/fixtures/ra_orgs_data.json
    """
    Organization = apps.get_model('network', 'Organization')
    OrganizationAddress = apps.get_model('network', 'OrganizationAddress')
    OrganizationPhoneNumber = apps.get_model('network', 'OrganizationPhoneNumber')
    Address = apps.get_model('locations', 'Address')
    Subdivision = apps.get_model('locations', 'Subdivision')

    # Determine the path to the JSON file
    current_dir = Path(__file__).parent.parent
    json_path = current_dir / 'fixtures' / 'ra-orgs.json'

    if not json_path.exists():
        print(f"Warning: RA organizations data file not found at {json_path}")
        print("Skipping RA organizations import.")
        raise Exception("RA organizations data file not found")

    # Load the JSON data
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Insert data into the database
    for organization_data in data:
        organization_name = organization_data.get("organization_name")
        addresses = organization_data.get("addresses", [])

        if organization_name == 'Recognized Organization Address':
            continue

        if len(addresses) == 0:
            continue

        # Get or create organization
        organization_slug = slugify(organization_name[:50])
        organization, _created = Organization.objects.get_or_create(
            slug=organization_slug,
            defaults={
                'name': organization_name,
                'organization_type': "community-organization",
                'is_active': True
            }
        )

        for index, address_data in enumerate(addresses):
            is_primary = index == 0
            subdivision_code = f"US-{address_data.get('state')}"
            phone_number = address_data.get("phone_number")
            address_name = address_data.get("address_name")
            line1 = address_data.get("line1")
            city = address_data.get("city")
            postal_code = address_data.get("postal_code")

            try:
                subdivision = Subdivision.objects.get(code=subdivision_code)
            except Subdivision.DoesNotExist:
                print(f"Warning: Subdivision {subdivision_code} not found, skipping address for {organization_name}")
                continue

            address = Address.objects.create(
                address_name=address_name,
                line1=line1,
                city=city,
                postal_code=postal_code,
                subdivision=subdivision,
            )

            OrganizationAddress.objects.get_or_create(
                organization=organization,
                address=address,
                defaults={'is_primary': is_primary}
            )

            if phone_number:
                OrganizationPhoneNumber.objects.get_or_create(
                    organization=organization,
                    phone_number=phone_number,
                    defaults={'is_primary': is_primary}
                )

    print(f"Imported {len(data)} RA organizations")


def load_probono_organizations(apps, schema_editor):
    """
    Load pro bono organization data from JSON file.

    Place your JSON file at: api/network/fixtures/probono_clean.json
    Generated by: python manage.py extract_probono <html_path> --out api/network/fixtures/probono_clean.json
    """
    Organization = apps.get_model('network', 'Organization')
    OrganizationAddress = apps.get_model('network', 'OrganizationAddress')
    OrganizationPhoneNumber = apps.get_model('network', 'OrganizationPhoneNumber')
    OrganizationEmail = apps.get_model('network', 'OrganizationEmail')
    OrganizationWebsites = apps.get_model('network', 'OrganizationWebsites')
    Address = apps.get_model('locations', 'Address')
    Subdivision = apps.get_model('locations', 'Subdivision')

    # Determine the path to the JSON file
    current_dir = Path(__file__).parent.parent
    json_path = current_dir / 'fixtures' / 'probono_clean.json'

    if not json_path.exists():
        print(f"Warning: Pro bono organizations data file not found at {json_path}")
        print("Skipping pro bono organizations import.")
        raise Exception("Pro bono organizations data file not found")

    # Load the JSON data
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Insert data into the database
    for org in data:
        telephone_numbers = org.get('telephone_numbers', [])
        emails = org.get('email_addresses', [])
        websites = org.get('websites', [])
        notes = org.get('notes', [])
        address_line = org.get('address', '')
        city = org.get('city', '')
        state = org.get('state', '')
        zip_code = org.get('zip_code', '')
        org_name = org.get('organization_name', '')
        org_type = slugify(org.get('organization_type', ''))
        org_slug = slugify(org_name[:50])

        if not org_name:
            continue

        # Get or create organization
        organization, created = Organization.objects.get_or_create(
            slug=org_slug,
            defaults={
                'name': org_name,
                'organization_type': org_type,
                'notes': notes,
                'is_active': True,
                'has_pro_bono': True,
            }
        )

        if not created:
            # Update existing organization
            organization.organization_type = org_type
            organization.notes = notes
            organization.has_pro_bono = True
            organization.save()
            print(f"Updated {org_name}")

        # Add websites
        for website in websites:
            OrganizationWebsites.objects.get_or_create(
                organization=organization,
                website=website
            )

        # Add phone numbers
        for phone_number in telephone_numbers:
            OrganizationPhoneNumber.objects.get_or_create(
                organization=organization,
                phone_number=phone_number
            )

        # Add emails
        for email in emails:
            OrganizationEmail.objects.get_or_create(
                organization=organization,
                email=email
            )

        # Add address if we have the required data
        if not (address_line and city and state and zip_code):
            continue

        try:
            subdivision = Subdivision.objects.get(code=f"US-{state}")
        except Subdivision.DoesNotExist:
            print(f"Warning: Subdivision US-{state} not found, skipping {org_name} address")
            continue

        # Check if this address already exists for this organization
        existing_address = OrganizationAddress.objects.filter(
            organization=organization,
            address__line1=address_line,
            address__city=city,
            address__postal_code=zip_code
        ).exists()

        if not existing_address:
            # Try to get existing address or create new one
            address, _ = Address.objects.get_or_create(
                line1=address_line,
                city=city,
                subdivision=subdivision,
                postal_code=zip_code,
            )

            OrganizationAddress.objects.create(
                organization=organization,
                address=address,
                is_primary=True
            )

    print(f"Imported {len(data)} pro bono organizations")


def load_enrichment_data_from_csv(apps, schema_editor):
    """
    Load enrichment data from CSV file to update/enhance existing organizations.

    Place your CSV file at: api/network/fixtures/enriched-companies-clay.csv
    This function will match organizations by name and enrich them with additional data.
    """
    Organization = apps.get_model('network', 'Organization')
    OrganizationPhoneNumber = apps.get_model('network', 'OrganizationPhoneNumber')
    OrganizationEmail = apps.get_model('network', 'OrganizationEmail')
    OrganizationWebsites = apps.get_model('network', 'OrganizationWebsites')
    OrganizationSocialLink = apps.get_model('network', 'OrganizationSocialLink')
    Address = apps.get_model('locations', 'Address')
    OrganizationAddress = apps.get_model('network', 'OrganizationAddress')
    Subdivision = apps.get_model('locations', 'Subdivision')

    # US State name to abbreviation mapping
    US_STATE_MAP = {
        'alabama': 'AL', 'alaska': 'AK', 'arizona': 'AZ', 'arkansas': 'AR', 'california': 'CA',
        'colorado': 'CO', 'connecticut': 'CT', 'delaware': 'DE', 'florida': 'FL', 'georgia': 'GA',
        'hawaii': 'HI', 'idaho': 'ID', 'illinois': 'IL', 'indiana': 'IN', 'iowa': 'IA',
        'kansas': 'KS', 'kentucky': 'KY', 'louisiana': 'LA', 'maine': 'ME', 'maryland': 'MD',
        'massachusetts': 'MA', 'michigan': 'MI', 'minnesota': 'MN', 'mississippi': 'MS',
        'missouri': 'MO', 'montana': 'MT', 'nebraska': 'NE', 'nevada': 'NV', 'new hampshire': 'NH',
        'new jersey': 'NJ', 'new mexico': 'NM', 'new york': 'NY', 'north carolina': 'NC',
        'north dakota': 'ND', 'ohio': 'OH', 'oklahoma': 'OK', 'oregon': 'OR', 'pennsylvania': 'PA',
        'rhode island': 'RI', 'south carolina': 'SC', 'south dakota': 'SD', 'tennessee': 'TN',
        'texas': 'TX', 'utah': 'UT', 'vermont': 'VT', 'virginia': 'VA', 'washington': 'WA',
        'west virginia': 'WV', 'wisconsin': 'WI', 'wyoming': 'WY', 'district of columbia': 'DC',
        'puerto rico': 'PR', 'guam': 'GU', 'virgin islands': 'VI', 'american samoa': 'AS',
        'northern mariana islands': 'MP'
    }

    def normalize_state(state_input):
        """Convert state name or abbreviation to abbreviation."""
        if not state_input:
            return None

        state_clean = state_input.strip().upper()

        # If it's already a 2-letter abbreviation, return it
        if len(state_clean) == 2 and state_clean.isalpha():
            return state_clean

        # Try to match full state name (case-insensitive)
        state_lower = state_input.strip().lower()
        if state_lower in US_STATE_MAP:
            return US_STATE_MAP[state_lower]

        # If nothing matches, return None
        return None

    # Determine the path to the CSV file
    current_dir = Path(__file__).parent.parent
    csv_path = current_dir / 'fixtures' / 'enriched-companies-clay.csv'

    if not csv_path.exists():
        print(f"Warning: Enrichment CSV file not found at {csv_path}")
        print("Skipping enrichment data import.")
        return

    # Load and process CSV data
    enriched_count = 0
    created_count = 0

    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)

        for row in reader:
            org_name = row.get('Name', '').strip()
            if not org_name:
                continue

            description = row.get('Description', '').strip()
            primary_industry = row.get('Primary Industry', '').strip()
            size = row.get('Size', '').strip()
            org_type = row.get('Type', '').strip()
            location = row.get('Location', '').strip()
            country = row.get('Country', '').strip()
            domain = row.get('Domain', '').strip()
            linkedin_url = row.get('LinkedIn URL', '').strip()
            phone = row.get('Contact Phone Number Result', '').strip()

            # Social media URLs
            instagram_url = row.get('Social Media URLs Instagram Url', '').strip()
            linkedin_social = row.get('Social Media URLs Linkedin Url', '').strip()
            x_url = row.get('Social Media URLs X Url', '').strip()
            youtube_url = row.get('Social Media URLs Youtube Url', '').strip()

            # Try to find existing organization by name (case-insensitive fuzzy match)
            org_slug = slugify(org_name[:50])

            # Try exact slug match first
            organization = Organization.objects.filter(slug=org_slug).first()

            # If not found, try name match (case-insensitive)
            if not organization:
                organization = Organization.objects.filter(name__iexact=org_name).first()

            # If still not found, create new organization
            if not organization:
                organization = Organization.objects.create(
                    name=org_name,
                    slug=org_slug,
                    description=description,
                    organization_type=slugify(org_type) if org_type else 'non-profit',
                    is_active=True,
                )
                created_count += 1
                print(f"Created new organization: {org_name}")
            else:
                # Update existing organization with enrichment data
                updated = False

                if description and not organization.description:
                    organization.description = description
                    updated = True

                if org_type and not organization.organization_type:
                    organization.organization_type = slugify(org_type)
                    updated = True

                if updated:
                    organization.save()
                    enriched_count += 1

            # Add domain/website
            if domain:
                # Clean up domain to make it a full URL
                website_url = domain if domain.startswith('http') else f"https://{domain}"
                OrganizationWebsites.objects.get_or_create(
                    organization=organization,
                    website=website_url
                )

            # Add LinkedIn URL
            if linkedin_url and linkedin_url != 'Response':
                OrganizationWebsites.objects.get_or_create(
                    organization=organization,
                    website=linkedin_url
                )

            # Add phone number
            if phone:
                OrganizationPhoneNumber.objects.get_or_create(
                    organization=organization,
                    phone_number=phone
                )

            # Add social media links
            social_links = []
            if instagram_url and instagram_url not in ['Not Found', 'Response']:
                social_links.append(('instagram', instagram_url))
            if linkedin_social and linkedin_social not in ['Not Found', 'Response']:
                social_links.append(('linkedin', linkedin_social))
            if x_url and x_url not in ['Not Found', 'Response']:
                social_links.append(('twitter', x_url))
            if youtube_url and youtube_url not in ['Not Found', 'Response']:
                social_links.append(('youtube', youtube_url))

            for platform, url in social_links:
                OrganizationSocialLink.objects.get_or_create(
                    organization=organization,
                    platform=platform,
                    defaults={'link': url}
                )

            # Parse location if available and country is United States
            if location and country == 'United States':
                # Location format is typically "City, State" or "City, State Abbreviation"
                parts = [p.strip() for p in location.split(',')]
                if len(parts) >= 2:
                    city = parts[0]
                    # Handle cases like "Washington, District of Columbia" or "Houston, Texas" or "Houston, TX"
                    state_part = parts[1].strip()

                    # Normalize state to abbreviation
                    state_abbr = normalize_state(state_part)

                    if state_abbr:
                        # Try to find subdivision
                        subdivision_code = f"US-{state_abbr}"
                        try:
                            subdivision = Subdivision.objects.get(code=subdivision_code)

                            # Check if organization already has an address in this location
                            existing_address = OrganizationAddress.objects.filter(
                                organization=organization,
                                address__city__iexact=city,
                                address__subdivision=subdivision,
                                address__line1__iexact=f'No Address found for {org_name}'
                            ).first()

                            if not existing_address:
                                # Create a basic address entry
                                address, _ = Address.objects.get_or_create(
                                    city=city,
                                    subdivision=subdivision,
                                    line1=f'No Address found for {org_name}',
                                )

                                OrganizationAddress.objects.get_or_create(
                                    organization=organization,
                                    address=address
                                )
                        except Subdivision.DoesNotExist:
                            print(f"Warning: Subdivision {subdivision_code} not found for {org_name}")
                    else:
                        print(f"Warning: Could not normalize state '{state_part}' for {org_name}")

    print(f"Enrichment complete: {enriched_count} organizations updated, {created_count} organizations created")


